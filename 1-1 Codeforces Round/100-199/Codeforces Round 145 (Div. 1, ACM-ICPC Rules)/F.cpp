void solve(){
	ll n,m;
	cin>>n>>m;
	
	string s;
	cin>>s;
	
	vector<H_Segment_tree<ll>> sgm(26,H_Segment_tree<ll>(n,vector<ll>(n+1,0)));
	
	for(ll i=1;i<=n;i++)
		sgm[(ll)(s[i-1]-'a')].modify(i,i,1);
	
	vector<ll> cnt(27,0ll);
	
	while(m--){
		ll l,r;
		cin>>l>>r;
		
		for(ll i=0;i<26;i++)
			cnt[i]=0;
		
		for(ll i=0;i<26;i++)
			cnt[i]=sgm[i].query(l,r).sum;
		
		ll flag=2;
		for(ll i=0;i<26;i++)
			if(cnt[i]&1)
				flag--;
		
		if(flag<=0) continue;
		
		for(ll i=0;i<26;i++)
			sgm[i].modify(l,r,0);
		
		for(ll i=0;i<26;i++){
			ll tmp=cnt[i]/2;
			if(tmp){
				sgm[i].modify(l,l+tmp-1,1);
				sgm[i].modify(r-tmp+1,r,1);
			}
			if(cnt[i]&1)
				sgm[i].modify((l+r)/2,(l+r)/2,1);
			l+=tmp;
			r-=tmp;
		}
	}
	
	string ans="";
	
	for(ll i=1;i<=n;i++)
		for(ll j=0;j<26;j++)
			if(sgm[j].query(i,i).sum){
				ans+=(char)(j+'a');
				break;
			}
				
	cout<<ans<<endl;
}

