	cin>>n>>m>>k;
	ll ans=1;
	
	ans+=k*(k+1)/2;
	
	if(k){
		ans+=n*(2*k+n-1);
	}else if(n){
		ans+=1+n*(n-1);
	}
	
	if(n+k){
		ans+=m*(6*n+2*k+3*m-3);
	}else if(m){
		ans+=1+m*(3*m-3);
	}
	
